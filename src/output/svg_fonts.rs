//! Glyph advance widths for the fonts [`SvgFont`](super::SvgFont) supports.
//!
//! Generated: measured in Chromium at 1000 units per em, upright and
//! italic, from the fonts' published files. A width of 0 means the font has
//! no glyph for that character (the layout then uses a generic estimate).

/// Advance widths for one font, in 1/1000 em.
pub(super) struct FontMetrics {
    /// ASCII 32..=126, upright.
    pub roman: [u16; 95],
    /// ASCII 32..=126, italic.
    pub italic: [u16; 95],
    /// Other characters, sorted: `(char, upright, italic)`.
    pub extra: &'static [(char, u16, u16)],
}

impl FontMetrics {
    /// The advance width in ems, if the font has the glyph.
    pub fn width(&self, c: char, italic: bool) -> Option<f32> {
        let units = if (' '..='~').contains(&c) {
            let i = c as usize - 32;
            if italic { self.italic[i] } else { self.roman[i] }
        } else {
            let i = self.extra.binary_search_by(|(k, _, _)| k.cmp(&c)).ok()?;
            let (_, r, it) = self.extra[i];
            if italic { it } else { r }
        };
        (units > 0).then(|| units as f32 / 1000.0)
    }
}

